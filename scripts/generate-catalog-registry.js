#!/usr/bin/env node

"use strict";

// Writes the conventional entries of the primary demo registries (components/website/registry):
// one `slug: dynamic(() => import("…/demos/<dir>/<slug>-demo"), { ssr: false })` line per
// manifest entry, in manifest order, between the generated-region markers of each category's
// table. Entries that differ (a named export, a shared demo, another file name) stay by hand
// below the region, each with its reason; the generator skips a slug the hand-written part
// already has. Projects are not generated: their registry waits for the owner (C-7).
// `--check` fails when a region differs from what it would write (pnpm run verify:catalog runs
// it; pnpm run fix:generated --only catalog-registry rewrites the regions).

const { existsSync, readFileSync, writeFileSync } = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const { loadComponentManifest } = require("./verify-component-catalog");

const REGISTRIES = Object.freeze([
	{ category: "arts", demoDir: "arts", file: "components/website/registry/arts.ts", table: "ARTS_DEMOS" },
	{ category: "blocks", demoDir: "blocks", file: "components/website/registry/blocks.ts", table: "BLOCK_DEMOS" },
	{ category: "ui", demoDir: "ui", file: "components/website/registry/ui/primary.ts", table: "UI_PRIMARY_DEMOS" },
	{ category: "ui-custom", demoDir: "ui-custom", file: "components/website/registry/ui-custom/primary.ts", table: "UI_CUSTOM_PRIMARY_DEMOS" },
	// ui-charts quotes every key, as the file always has.
	{ category: "ui-charts", demoDir: "ui-charts", file: "components/website/registry/ui-charts.ts", quoteKeys: true, table: "UI_CHARTS_DEMO" },
	{ category: "utility", demoDir: "utils", file: "components/website/registry/utility.ts", table: "UTILITY_DEMOS" },
	// visual writes the options on their own lines, as most of its entries always have.
	{ blockOptions: true, category: "visual", demoDir: "visual", file: "components/website/registry/visual.ts", table: "VISUAL_DEMOS" },
]);

const BEGIN = "\t// <generated: catalog-registry>";
const END = "\t// </generated: catalog-registry>";
const HEADER = [
	"\t// Generated by scripts/generate-catalog-registry.js from app/data/component-manifest.ts: one entry",
	"\t// per manifest slug whose demo is <slug>-demo. Do not edit inside these markers; add the manifest",
	"\t// entry and the demo, then run pnpm run fix:generated --only catalog-registry. Entries that differ",
	"\t// go below the region, by hand, each with its reason.",
];

function toObjectKey(slug, { quoteKeys = false } = {}) {
	return !quoteKeys && /^[A-Za-z_$][\w$]*$/u.test(slug) ? slug : JSON.stringify(slug);
}

function renderEntry(registry, slug) {
	const head = `\t${toObjectKey(slug, registry)}: dynamic(() => import("${demoImportPath(registry, slug)}"), `;
	return registry.blockOptions ? `${head}{\n\t\tssr: false,\n\t}),` : `${head}{ ssr: false }),`;
}

function demoImportPath(registry, slug) {
	const fromDir = path.posix.dirname(registry.file);
	const relative = path.posix.relative(fromDir, `components/website/demos/${registry.demoDir}/${slug}-demo`);
	return relative.startsWith(".") ? relative : `./${relative}`;
}

function findTable(sourceFile, table) {
	let found = null;
	sourceFile.forEachChild((node) => {
		if (!ts.isVariableStatement(node)) return;
		for (const declaration of node.declarationList.declarations) {
			if (declaration.name.getText(sourceFile) === table && declaration.initializer && ts.isObjectLiteralExpression(declaration.initializer)) {
				found = declaration.initializer;
			}
		}
	});
	return found;
}

function propertyKey(property, sourceFile) {
	const name = property.name;
	if (!name) return null;
	if (ts.isStringLiteral(name) || ts.isIdentifier(name)) return name.text;
	return name.getText(sourceFile);
}

// The table's source split around the generated region, and the keys written by hand.
function readRegion(registry, source) {
	const begin = source.indexOf(`${BEGIN}\n`);
	const end = source.indexOf(`${END}\n`);
	if (begin === -1 || end === -1 || end < begin) return { problem: `${registry.file}: generated-region markers are missing in ${registry.table}` };
	const sourceFile = ts.createSourceFile(registry.file, source, ts.ScriptTarget.Latest, true);
	const table = findTable(sourceFile, registry.table);
	if (!table || table.getStart(sourceFile) > begin || table.getEnd() < end) {
		return { problem: `${registry.file}: the generated region is not inside ${registry.table}` };
	}
	const regionEnd = end + END.length + 1;
	const handKeys = new Set();
	for (const property of table.properties) {
		const start = property.getStart(sourceFile);
		if (start > begin && start < regionEnd) continue;
		const key = propertyKey(property, sourceFile);
		if (key) handKeys.add(key);
	}
	return { after: source.slice(regionEnd), before: source.slice(0, begin), handKeys };
}

function renderRegion(registry, components, handKeys, { cwd = process.cwd() } = {}) {
	const problems = [];
	const lines = [];
	for (const { slug } of components.filter((component) => component.category === registry.category)) {
		if (handKeys.has(slug)) continue;
		const demoFile = `components/website/demos/${registry.demoDir}/${slug}-demo.tsx`;
		if (!existsSync(path.join(cwd, demoFile))) {
			problems.push(`${registry.category}/${slug}: ${demoFile} is missing; add it, or write the entry by hand below the generated region with its reason`);
			continue;
		}
		lines.push(renderEntry(registry, slug));
	}
	return { problems, region: [BEGIN, ...HEADER, ...lines, END, ""].join("\n") };
}

function renderRegistry(registry, components, { cwd = process.cwd() } = {}) {
	const filePath = path.join(cwd, registry.file);
	const current = readFileSync(filePath, "utf8");
	const parts = readRegion(registry, current);
	if (parts.problem) return { current, problems: [parts.problem], source: null };
	const { problems, region } = renderRegion(registry, components, parts.handKeys, { cwd });
	return { current, problems, source: problems.length > 0 ? null : `${parts.before}${region}${parts.after}` };
}

function main(argv = process.argv.slice(2), { cwd = process.cwd(), components = null, log = console.log, error = console.error, registries = REGISTRIES } = {}) {
	const check = argv.includes("--check");
	const entries = components ?? loadComponentManifest(cwd).components;
	let failed = false;
	for (const registry of registries) {
		const { current, problems, source } = renderRegistry(registry, entries, { cwd });
		if (problems.length > 0) {
			failed = true;
			error(`${registry.file}: cannot generate:\n${problems.map((problem) => `- ${problem}`).join("\n")}`);
			continue;
		}
		if (source === current) continue;
		if (check) {
			failed = true;
			error(`${registry.file} is stale. Run: pnpm run fix:generated --only catalog-registry`);
			continue;
		}
		writeFileSync(path.join(cwd, registry.file), source);
		log(`Wrote ${registry.file}.`);
	}
	if (!failed && check) log(`Catalog registry regions are current (${registries.map((registry) => registry.category).join(", ")}).`);
	return failed ? 1 : 0;
}

if (require.main === module) {
	process.exitCode = main();
}

module.exports = { BEGIN, END, REGISTRIES, main, renderRegion, renderRegistry };
