const globCache = new Map();

export function globToRegExp(glob) {
	let cached = globCache.get(glob);
	if (cached) return cached;
	let source = "";
	for (let index = 0; index < glob.length; index += 1) {
		const char = glob[index];
		if (char === "*" && glob[index + 1] === "*") {
			if (glob[index + 2] === "/") {
				source += "(?:.*/)?";
				index += 2;
			} else {
				source += ".*";
				index += 1;
			}
		} else if (char === "*") {
			source += "[^/]*";
		} else if (char === "{") {
			const end = glob.indexOf("}", index);
			if (end === -1) throw new Error(`unclosed brace in glob ${glob}`);
			const options = glob.slice(index + 1, end).split(",").map((option) => option.replace(/[.+?^${}()|[\]\\]/gu, "\\$&"));
			source += `(?:${options.join("|")})`;
			index = end;
		} else {
			source += char.replace(/[.+?^${}()|[\]\\]/gu, "\\$&");
		}
	}
	cached = new RegExp(`^${source}$`, "u");
	globCache.set(glob, cached);
	return cached;
}

export function matchesAny(filePath, globs) {
	return globs.some((glob) => globToRegExp(glob).test(filePath));
}

// Returns the lowercase repo-relative path used for matching, or null when the path is
// not a plain ASCII relative path.
export function normalizePath(rawPath) {
	if (typeof rawPath !== "string" || !rawPath) return null;
	if (/[^\x20-\x7e]/u.test(rawPath) || rawPath.includes("\\") || rawPath.startsWith("/")) return null;
	let normalized = rawPath;
	while (normalized.startsWith("./")) normalized = normalized.slice(2);
	const segments = normalized.split("/");
	if (segments.some((segment) => segment === ".." || segment === "." || segment === "")) return null;
	return normalized.toLowerCase();
}

function isDenied(normalized, policy) {
	if (matchesAny(normalized, policy.generatedCompanions.globs)) return false;
	const basename = normalized.slice(normalized.lastIndexOf("/") + 1);
	return matchesAny(normalized, policy.deny) || policy.denyBasenames.some((pattern) => pattern.test(basename));
}

function isCount(value) {
	return Number.isInteger(value) && value >= 0;
}

// True when `headText` only drops entries from, or lowers counts in, `baseText`; this is
// what `eslint --prune-suppressions` produces. Both must parse as `{ file: { rule: { count } } }`.
export function isPrunedSuppressions(baseText, headText) {
	let base;
	let head;
	try {
		base = JSON.parse(baseText);
		head = JSON.parse(headText);
	} catch {
		return false;
	}
	const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
	if (!isObject(base) || !isObject(head)) return false;
	for (const [file, rules] of Object.entries(head)) {
		if (!isObject(rules) || !Object.hasOwn(base, file) || !isObject(base[file])) return false;
		for (const [rule, entry] of Object.entries(rules)) {
			const baseEntry = base[file][rule];
			if (!isObject(entry) || !isObject(baseEntry) || Object.keys(entry).join() !== "count") return false;
			if (!isCount(entry.count) || !isCount(baseEntry.count) || entry.count > baseEntry.count) return false;
		}
	}
	return true;
}

// Splits a changed file into the path halves the policy evaluates.
function fileHalves(file) {
	if (file.status === "renamed" || file.status === "copied") {
		return [
			{ path: file.previousPath, status: "removed" },
			{ path: file.path, status: "added" },
		];
	}
	return [{ path: file.path, status: file.status }];
}

function classifyHalf(half, file, policy) {
	const normalized = normalizePath(half.path);
	if (!normalized) return { category: "rejected", reason: `${JSON.stringify(half.path ?? null)} is not a plain ASCII relative path` };
	if (isDenied(normalized, policy)) return { category: "denied", reason: `${half.path} is on the denylist` };
	const allowed = (rule) => matchesAny(normalized, rule.globs);
	const statusOk = (rule) => rule.statuses.includes(half.status);

	if (allowed(policy.pruneOnly)) {
		if (!statusOk(policy.pruneOnly)) return { category: "rejected", reason: `${half.path} may only be modified (${half.status})` };
		return isPrunedSuppressions(file.baseContent, file.headContent)
			? { category: "prune-only" }
			: { category: "rejected", reason: `${half.path} may only drop entries or lower counts, or its contents were unavailable` };
	}
	if (allowed(policy.generatedCompanions)) {
		return statusOk(policy.generatedCompanions)
			? { category: "generated" }
			: { category: "rejected", reason: `${half.path} is generated and may only be modified (${half.status})` };
	}
	if (allowed(policy.allow.test)) {
		return statusOk(policy.allow.test)
			? { category: "test" }
			: { category: "rejected", reason: `${half.path}: a ${half.status} test file needs a human` };
	}
	if (allowed(policy.allow.doc)) {
		return statusOk(policy.allow.doc)
			? { category: "doc" }
			: { category: "rejected", reason: `${half.path}: a ${half.status} doc needs a human` };
	}
	return { category: "rejected", reason: `${half.path} is outside the low-risk allowlist` };
}

function classifyFile(file, policy) {
	if (!isCount(file.additions) || !isCount(file.deletions)) {
		return { category: "rejected", reasons: [`${file.path} has no line counts`] };
	}
	const results = fileHalves(file).map((half) => classifyHalf(half, file, policy));
	const reasons = results.filter((result) => result.reason).map((result) => result.reason);
	return reasons.length > 0
		? { category: results.find((result) => result.reason).category, reasons }
		: { category: results.at(-1).category, reasons: [] };
}

/**
 * @param {object} pr normalized PR: { number, state, author, labels[], isDraft, baseRefName,
 *   headRefName, headRepository ("owner/name"), headRefOid, changedFiles?, headAfterFiles?,
 *   files[{ path, previousPath?, status, additions, deletions, baseContent?, headContent? }] }
 * @param {object} context { repository ("owner/name"), defaultBranch, requireGrantLabel?, expectedHead? }
 */
export function evaluateEligibility(pr, { repository, defaultBranch, requireGrantLabel = true, expectedHead }, policy = MERGE_POLICY) {
	const reasons = [];
	const owner = repository.split("/")[0].toLowerCase();
	const labels = new Set(pr.labels ?? []);

	const requiredLabels = requireGrantLabel
		? policy.requiredLabels
		: policy.requiredLabels.filter((label) => label !== policy.labelGrantedByPolicy);
	for (const label of requiredLabels) {
		if (!labels.has(label)) reasons.push(`missing label ${label}`);
	}
	for (const label of policy.blockingLabels) {
		if (labels.has(label)) reasons.push(`blocking label ${label}`);
	}
	if (String(pr.state ?? "").toUpperCase() !== "OPEN") reasons.push(`PR is ${String(pr.state ?? "unknown").toLowerCase()}`);
	if (pr.isDraft !== false) reasons.push("PR is a draft");
	if (pr.baseRefName !== defaultBranch) reasons.push(`base ${pr.baseRefName} is not the default branch ${defaultBranch}`);
	if ((pr.headRepository ?? "").toLowerCase() !== repository.toLowerCase()) {
		reasons.push(`head repository ${pr.headRepository || "(unknown)"} is not ${repository}`);
	}
	if (!String(pr.headRefName ?? "").startsWith(policy.headBranchPrefix)) {
		reasons.push(`head branch ${pr.headRefName || "(unknown)"} does not start with ${policy.headBranchPrefix}`);
	}
	if ((pr.author ?? "").toLowerCase() !== owner) reasons.push(`author ${pr.author || "(unknown)"} is not the repo owner ${owner}`);
	if (expectedHead && pr.headRefOid !== expectedHead) reasons.push(`head ${pr.headRefOid} is not the expected ${expectedHead}`);
	if (pr.headAfterFiles !== undefined && pr.headAfterFiles !== pr.headRefOid) {
		reasons.push(`head moved from ${pr.headRefOid} to ${pr.headAfterFiles} while reading files`);
	}

	const files = pr.files ?? [];
	if (files.length === 0) reasons.push("PR changes no files");
	if (!Number.isInteger(pr.changedFiles) || pr.changedFiles !== files.length) {
		reasons.push(`file list incomplete (${files.length} of ${pr.changedFiles ?? "unknown"})`);
	}

	const classified = files.map((file) => {
		const { category, reasons: fileReasons } = classifyFile(file, policy);
		reasons.push(...fileReasons);
		return { path: file.path, previousPath: file.previousPath, status: file.status, category };
	});
	const hasPrimary = classified.some((file) => ["test", "doc", "prune-only"].includes(file.category));
	if (files.length > 0 && !hasPrimary && classified.every((file) => file.category === "generated")) {
		reasons.push("only generated files changed; they are eligible only beside a low-risk change");
	}

	const changedLines = files.reduce((sum, file) => sum + (isCount(file.additions) ? file.additions : 0) + (isCount(file.deletions) ? file.deletions : 0), 0);
	if (changedLines > policy.maxChangedLines) {
		reasons.push(`${changedLines} changed lines exceed the ${policy.maxChangedLines}-line limit`);
	}

	return {
		eligible: reasons.length === 0,
		number: pr.number,
		headRefOid: pr.headRefOid,
		mode: requireGrantLabel ? "merge" : "policy",
		changedLines,
		reasons,
		files: classified,
	};
}

