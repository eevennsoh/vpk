#!/usr/bin/env node

// Decides whether a Codex automation pull request is low-risk enough for the
// `automation-merge` job to merge it after the vpk-git-ship review gate (decision D11 in
// `.agents/docs/hardening-record.md`). It never merges anything itself. Producers run it
// with `--policy` on their own PR to choose `automerge:allowed` or `risk:needs-human`; the
// merger runs it without `--policy`, which also requires the `automerge:allowed` label.
//
//   node scripts/automation-merge-eligibility.mjs --pr <number> --repo <owner/name> [--policy] [--json]
//
// Exit 0 eligible, 2 ineligible, 1 error.

import { execFile } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

// ---------------------------------------------------------------------------------------
// Policy. Paths are repo-relative globs: `*` stays inside one path segment, `**` crosses
// segments. A file must match an allow category and no deny pattern; deny always wins.
// ---------------------------------------------------------------------------------------
export const MERGE_POLICY = {
	requiredLabels: ["automation", "automerge:allowed"],
	// `--policy` (producer self-check) drops this one label from the requirement, since the
	// producer applies it only after the check passes.
	labelGrantedByPolicy: "automerge:allowed",
	blockingLabels: ["automerge:blocked", "risk:needs-human", "review:changes-requested"],
	maxChangedLines: 300,
	allow: {
		test: ["**/*.test.*", "tests/**"],
		doc: ["**/*.md"],
	},
	// Markdown that steers agents or the product, so it always needs a human.
	docExceptions: [
		"**/AGENTS.md",
		"**/CLAUDE.md",
		"**/DESIGN.md",
		"**/WORKFLOW.md",
		".agents/rules/**",
		".agents/skills/**/SKILL.md",
	],
	// Baselines that may only shrink: every added line must lower a removed `"count"` line.
	pruneOnly: ["eslint-suppressions.json"],
	// Regenerated by `pnpm run fix:generated`; eligible only beside an otherwise-eligible file.
	generatedCompanions: [".agents/knowledge/**", ".agents/skills/INDEX.md"],
	// Deleting a test removes coverage, so it needs a human even though editing one does not.
	allowTestDeletion: false,
	deny: [
		// Server boundary
		"backend/routes/**",
		"backend/middleware/**",
		// Auth, identity, and secrets
		"**/auth/**",
		"**/auth-*",
		"**/*-auth.*",
		"**/*-auth-*",
		"**/*slauth*",
		"**/*asap*",
		"**/*identity*",
		"**/*credential*",
		"**/*secret*",
		"**/*.env*",
		"**/.env*",
		// Dependencies and registry
		"**/package.json",
		"pnpm-lock.yaml",
		"pnpm-workspace.yaml",
		"**/.npmrc",
		// CI and the gates it runs
		".github/**",
		"eslint.config.mjs",
		"scripts/check.mjs",
		"scripts/run-parallel.mjs",
		"scripts/run-js-unit-tests*",
		"scripts/js-unit-test-*",
		"scripts/generated-artifacts*",
		"scripts/verify-*",
		"scripts/validate-*",
		"scripts/eslint-*",
		"scripts/perf-*",
		"scripts/collect-route-transfer*",
		"scripts/write-npmrc*",
		"scripts/lib/heavy-run-lock*",
		"scripts/automation-merge-eligibility*",
		// The merge gate, the producer policy, and the job definitions themselves
		".agents/skills/vpk-git-ship/**",
		".agents/skills/vpk-scheduled-automation/**",
		".agents/automations/**",
		// Unattended automation must never modify durable deliverables
		"artifacts/**",
	],
};

