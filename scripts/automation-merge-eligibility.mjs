const globCache = new Map();

export function globToRegExp(glob) {
	let cached = globCache.get(glob);
	if (cached) return cached;
	let source = "";
	for (let index = 0; index < glob.length; index += 1) {
		const char = glob[index];
		if (char === "*" && glob[index + 1] === "*") {
			if (glob[index + 2] === "/") {
				source += "(?:.*/)?";
				index += 2;
			} else {
				source += ".*";
				index += 1;
			}
		} else if (char === "*") {
			source += "[^/]*";
		} else {
			source += char.replace(/[.+?^${}()|[\]\\]/gu, "\\$&");
		}
	}
	cached = new RegExp(`^${source}$`, "u");
	globCache.set(glob, cached);
	return cached;
}

export function matchesAny(filePath, globs) {
	return globs.some((glob) => globToRegExp(glob).test(filePath));
}

const COUNT_LINE = /^\s*"count":\s*(\d+)\s*,?\s*$/u;

// True when the unified diff only removes lines or lowers `"count"` values, which is what
// `eslint --prune-suppressions` produces.
export function isPruneOnlyPatch(patch) {
	if (typeof patch !== "string" || !patch) return false;
	let removedCounts = [];
	let sawRemoval = false;
	for (const line of patch.split("\n")) {
		if (line.startsWith("@@")) {
			removedCounts = [];
			continue;
		}
		if (line.startsWith("-")) {
			sawRemoval = true;
			const match = COUNT_LINE.exec(line.slice(1));
			if (match) removedCounts.push(Number(match[1]));
			continue;
		}
		if (line.startsWith("+")) {
			const match = COUNT_LINE.exec(line.slice(1));
			if (!match || removedCounts.length === 0) return false;
			const previous = removedCounts.shift();
			if (Number(match[1]) >= previous) return false;
			continue;
		}
		// A context line ends the pairing window for count replacements.
		removedCounts = [];
	}
	return sawRemoval;
}

function classifyFile(file, policy) {
	const paths = [file.path, file.previousPath].filter(Boolean);
	const denied = paths.find((candidate) => matchesAny(candidate, policy.deny));
	if (denied) return { category: "denied", reason: `${denied} is on the denylist` };

	if (matchesAny(file.path, policy.pruneOnly)) {
		return isPruneOnlyPatch(file.patch)
			? { category: "prune-only" }
			: { category: "rejected", reason: `${file.path} may only shrink (deleted lines or lowered counts), or its patch was unavailable` };
	}
	if (matchesAny(file.path, policy.generatedCompanions)) return { category: "generated" };
	if (matchesAny(file.path, policy.allow.test)) {
		if (file.status === "removed" && !policy.allowTestDeletion) {
			return { category: "rejected", reason: `${file.path} deletes a test` };
		}
		return { category: "test" };
	}
	if (matchesAny(file.path, policy.allow.doc)) {
		return matchesAny(file.path, policy.docExceptions)
			? { category: "rejected", reason: `${file.path} is agent or product policy markdown` }
			: { category: "doc" };
	}
	return { category: "rejected", reason: `${file.path} is outside the low-risk allowlist` };
}

/**
 * @param {object} pr normalized PR: { number, state, author, labels[], isDraft, baseRefName,
 *   headRepository ("owner/name"), headRefOid, changedFiles?, files[{ path, previousPath?,
 *   status, additions, deletions, patch? }] }
 * @param {object} context { repository ("owner/name"), defaultBranch, requireGrantLabel? }
 */
export function evaluateEligibility(pr, { repository, defaultBranch, requireGrantLabel = true }, policy = MERGE_POLICY) {
	const reasons = [];
	const owner = repository.split("/")[0].toLowerCase();
	const labels = new Set(pr.labels ?? []);

	const requiredLabels = requireGrantLabel
		? policy.requiredLabels
		: policy.requiredLabels.filter((label) => label !== policy.labelGrantedByPolicy);
	for (const label of requiredLabels) {
		if (!labels.has(label)) reasons.push(`missing label ${label}`);
	}
	for (const label of policy.blockingLabels) {
		if (labels.has(label)) reasons.push(`blocking label ${label}`);
	}
	if (pr.state && pr.state.toUpperCase() !== "OPEN") reasons.push(`PR is ${pr.state.toLowerCase()}`);
	if (pr.isDraft) reasons.push("PR is a draft");
	if (pr.baseRefName !== defaultBranch) reasons.push(`base ${pr.baseRefName} is not the default branch ${defaultBranch}`);
	if ((pr.headRepository ?? "").toLowerCase() !== repository.toLowerCase()) {
		reasons.push(`head repository ${pr.headRepository || "(unknown)"} is not ${repository}`);
	}
	if ((pr.author ?? "").toLowerCase() !== owner) reasons.push(`author ${pr.author || "(unknown)"} is not the repo owner ${owner}`);

	const files = pr.files ?? [];
	if (files.length === 0) reasons.push("PR changes no files");
	if (Number.isInteger(pr.changedFiles) && pr.changedFiles !== files.length) {
		reasons.push(`file list incomplete (${files.length} of ${pr.changedFiles})`);
	}

	const classified = files.map((file) => ({ path: file.path, ...classifyFile(file, policy) }));
	for (const file of classified) {
		if (file.reason) reasons.push(file.reason);
	}
	const hasPrimary = classified.some((file) => ["test", "doc", "prune-only"].includes(file.category));
	if (files.length > 0 && !hasPrimary && classified.every((file) => file.category === "generated")) {
		reasons.push("only generated files changed; they are eligible only beside a low-risk change");
	}

	const changedLines = files.reduce((sum, file) => sum + (file.additions ?? 0) + (file.deletions ?? 0), 0);
	if (changedLines > policy.maxChangedLines) {
		reasons.push(`${changedLines} changed lines exceed the ${policy.maxChangedLines}-line limit`);
	}

	return {
		eligible: reasons.length === 0,
		number: pr.number,
		headRefOid: pr.headRefOid,
		mode: requireGrantLabel ? "merge" : "policy",
		changedLines,
		reasons,
		files: classified,
	};
}

