#!/usr/bin/env node

"use strict";

// Writes the detail barrels app/data/details/{blocks,ui,ui-custom}.ts: one import and one
// record per manifest entry of the category, in manifest order, from the leaf files in
// app/data/details/<category>/. The leaves hold the content; the barrels only list them, so a
// new entry adds its manifest line and its leaf, and this regenerates the barrel.
// `--check` fails when a barrel differs from what it would write (pnpm run verify:catalog runs
// it; pnpm run fix:generated --only catalog-barrels rewrites them).

const { existsSync, readFileSync, readdirSync, writeFileSync } = require("node:fs");
const path = require("node:path");

const { loadComponentManifest } = require("./verify-component-catalog");

const BARREL_CATEGORIES = Object.freeze({
	blocks: "BLOCK_DETAILS",
	ui: "UI_DETAILS",
	"ui-custom": "UI_CUSTOM_DETAILS",
});

// Leaf files whose name is not the slug, each with its reason.
const LEAF_FILE_OVERRIDES = Object.freeze({
	// Historical file name; tests read it through app/data/details/test-source.cjs.
	"ui/icon": "icon-detail",
});

// Leaves that export a detail no manifest entry uses, each with its reason. A new one fails.
const UNUSED_LEAVES = Object.freeze({
	// No catalog entry since b565d0f57; whether to delete them is the owner's call (C-7).
	"blocks/ide": "detail without a catalog entry",
	"ui/code": "detail without a catalog entry",
});

const LEAF_EXPORT = /^export const ([A-Z0-9_]+_DETAIL)\b/mu;

function toObjectKey(slug) {
	return /^[A-Za-z_$][\w$]*$/u.test(slug) ? slug : JSON.stringify(slug);
}

function leafFileName(category, slug) {
	return LEAF_FILE_OVERRIDES[`${category}/${slug}`] ?? slug;
}

function readLeafExport(category, fileName, cwd) {
	const leafPath = path.join(cwd, "app/data/details", category, `${fileName}.ts`);
	if (!existsSync(leafPath)) return null;
	return LEAF_EXPORT.exec(readFileSync(leafPath, "utf8"))?.[1] ?? null;
}

// The barrel for one category, or the problems that stop it from being written.
function renderBarrel(category, components, { cwd = process.cwd() } = {}) {
	const exportName = BARREL_CATEGORIES[category];
	const entries = components.filter((component) => component.category === category);
	const problems = [];
	const records = [];
	for (const { slug } of entries) {
		const fileName = leafFileName(category, slug);
		const detailExport = readLeafExport(category, fileName, cwd);
		if (!detailExport) {
			problems.push(`${category}/${slug}: app/data/details/${category}/${fileName}.ts is missing or exports no *_DETAIL constant`);
			continue;
		}
		records.push({ detailExport, fileName, slug });
	}

	// A leaf that exports a detail but has no manifest entry would silently drop out of the barrel.
	const used = new Set(records.map((record) => record.fileName));
	const leafDir = path.join(cwd, "app/data/details", category);
	for (const file of existsSync(leafDir) ? readdirSync(leafDir, { withFileTypes: true }) : []) {
		if (!file.isFile() || !file.name.endsWith(".ts")) continue;
		const fileName = file.name.replace(/\.ts$/u, "");
		if (!used.has(fileName) && !UNUSED_LEAVES[`${category}/${fileName}`] && readLeafExport(category, fileName, cwd)) {
			problems.push(`app/data/details/${category}/${file.name} exports a detail but no ${category} manifest entry uses it`);
		}
	}
	if (problems.length > 0) return { problems, source: null };

	const lines = [
		"// Generated by scripts/generate-catalog-barrels.js from app/data/component-manifest.ts and the",
		`// leaf files in ./${category}/. Do not edit: add the manifest entry and the leaf, then run`,
		"// pnpm run fix:generated --only catalog-barrels.",
		"",
		'import type { ComponentDetail } from "@/app/data/component-detail-types";',
		"",
		...records.map(({ detailExport, fileName }) => `import { ${detailExport} } from "./${category}/${fileName}";`),
		"",
		`export const ${exportName}: Record<string, ComponentDetail> = {`,
		...records.map(({ detailExport, slug }) => `\t${toObjectKey(slug)}: ${detailExport},`),
		"};",
		"",
	];
	return { problems: [], source: lines.join("\n") };
}

function barrelPath(category, cwd) {
	return path.join(cwd, "app/data/details", `${category}.ts`);
}

function main(argv = process.argv.slice(2), { cwd = process.cwd(), components = null, log = console.log, error = console.error } = {}) {
	const check = argv.includes("--check");
	const entries = components ?? loadComponentManifest(cwd).components;
	let failed = false;
	for (const category of Object.keys(BARREL_CATEGORIES)) {
		const { problems, source } = renderBarrel(category, entries, { cwd });
		const relative = `app/data/details/${category}.ts`;
		if (problems.length > 0) {
			failed = true;
			error(`${relative}: cannot generate:\n${problems.map((problem) => `- ${problem}`).join("\n")}`);
			continue;
		}
		const current = existsSync(barrelPath(category, cwd)) ? readFileSync(barrelPath(category, cwd), "utf8") : null;
		if (current === source) continue;
		if (check) {
			failed = true;
			error(`${relative} is stale. Run: pnpm run fix:generated --only catalog-barrels`);
			continue;
		}
		writeFileSync(barrelPath(category, cwd), source);
		log(`Wrote ${relative}.`);
	}
	if (!failed && check) log(`Catalog detail barrels are current (${Object.keys(BARREL_CATEGORIES).join(", ")}).`);
	return failed ? 1 : 0;
}

if (require.main === module) {
	process.exitCode = main();
}

module.exports = { BARREL_CATEGORIES, LEAF_FILE_OVERRIDES, UNUSED_LEAVES, main, renderBarrel };
