"use strict";

const assert = require("node:assert/strict");
const { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const path = require("node:path");
const test = require("node:test");

const { main, renderBarrel } = require("./generate-catalog-barrels");

function scratch(t, leaves) {
	const cwd = mkdtempSync(path.join(tmpdir(), "vpk-catalog-barrels-"));
	t.after(() => rmSync(cwd, { force: true, recursive: true }));
	for (const [file, source] of Object.entries(leaves)) {
		mkdirSync(path.dirname(path.join(cwd, "app/data/details", file)), { recursive: true });
		writeFileSync(path.join(cwd, "app/data/details", file), source);
	}
	return cwd;
}

const leaf = (name) => `import type { ComponentDetail } from "@/app/data/component-detail-types";\n\nexport const ${name}: ComponentDetail = { description: "x" };\n`;
const BLOCKS = [
	{ category: "blocks", slug: "zeta-card" },
	{ category: "blocks", slug: "agent" },
	{ category: "ui", slug: "icon" },
	{ category: "ui-custom", slug: "tile" },
];
const LEAVES = {
	"blocks/agent.ts": "import { createAgentDetail } from \"./agent-detail\";\n\nexport const AGENT_DETAIL = createAgentDetail();\n",
	"blocks/agent-detail.ts": "export function createAgentDetail() { return {}; }\n",
	"blocks/zeta-card.ts": leaf("ZETA_CARD_DETAIL"),
	"ui/icon-detail.ts": leaf("ICON_DETAIL"),
	"ui-custom/tile.ts": leaf("TILE_DETAIL"),
};

test("a barrel lists every manifest entry of its category in manifest order, from its leaf", (t) => {
	const cwd = scratch(t, LEAVES);
	const { problems, source } = renderBarrel("blocks", BLOCKS, { cwd });
	assert.deepEqual(problems, []);
	assert.equal(source, [
		"// Generated by scripts/generate-catalog-barrels.js from app/data/component-manifest.ts and the",
		"// leaf files in ./blocks/. Do not edit: add the manifest entry and the leaf, then run",
		"// pnpm run fix:generated --only catalog-barrels.",
		"",
		'import type { ComponentDetail } from "@/app/data/component-detail-types";',
		"",
		'import { ZETA_CARD_DETAIL } from "./blocks/zeta-card";',
		'import { AGENT_DETAIL } from "./blocks/agent";',
		"",
		"export const BLOCK_DETAILS: Record<string, ComponentDetail> = {",
		'\t"zeta-card": ZETA_CARD_DETAIL,',
		"\tagent: AGENT_DETAIL,",
		"};",
		"",
	].join("\n"));
	// A helper beside the leaves (no *_DETAIL export) is not an entry.
	assert.doesNotMatch(source, /agent-detail/u);
	// The record lines keep the shape app/data/details/test-source.cjs parses.
	assert.match(source, /^\t(?:"([^"]+)"|([A-Za-z_$][\w$]*)): [A-Z0-9_]+_DETAIL,$/mu);
});

test("a leaf whose file name is not the slug comes from the override table", (t) => {
	const cwd = scratch(t, LEAVES);
	assert.match(renderBarrel("ui", BLOCKS, { cwd }).source, /import \{ ICON_DETAIL \} from "\.\/ui\/icon-detail";\n[\s\S]*\ticon: ICON_DETAIL,/u);
});

test("a manifest entry without a leaf, or a leaf without an entry, stops the barrel", (t) => {
	const cwd = scratch(t, { ...LEAVES, "blocks/orphan.ts": leaf("ORPHAN_DETAIL") });
	const missing = renderBarrel("blocks", [...BLOCKS, { category: "blocks", slug: "missing" }], { cwd });
	assert.equal(missing.source, null);
	assert.deepEqual(missing.problems, [
		"blocks/missing: app/data/details/blocks/missing.ts is missing or exports no *_DETAIL constant",
		"app/data/details/blocks/orphan.ts exports a detail but no blocks manifest entry uses it",
	]);
});

test("--check fails on a stale barrel with the refresh command; a write makes it current", (t) => {
	const cwd = scratch(t, LEAVES);
	for (const category of ["blocks", "ui", "ui-custom"]) writeFileSync(path.join(cwd, `app/data/details/${category}.ts`), "// hand-edited\n");
	const errors = [];
	assert.equal(main(["--check"], { components: BLOCKS, cwd, error: (line) => errors.push(line), log: () => {} }), 1);
	assert.match(errors.join("\n"), /app\/data\/details\/blocks\.ts is stale\. Run: pnpm run fix:generated --only catalog-barrels/u);
	assert.equal(readFileSync(path.join(cwd, "app/data/details/blocks.ts"), "utf8"), "// hand-edited\n");

	assert.equal(main([], { components: BLOCKS, cwd, error: () => {}, log: () => {} }), 0);
	const logs = [];
	assert.equal(main(["--check"], { components: BLOCKS, cwd, error: () => {}, log: (line) => logs.push(line) }), 0);
	assert.match(logs.join("\n"), /barrels are current/u);
});
