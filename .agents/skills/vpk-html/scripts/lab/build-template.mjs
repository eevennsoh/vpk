#!/usr/bin/env node
// vpk-lab · generate assets/templates/motion-case-study.html (references/lab-kit.md, Template).
//
//   node .agents/skills/vpk-html/scripts/lab/build-template.mjs           # write (unsandboxed: writes under .agents/skills/)
//   node .agents/skills/vpk-html/scripts/lab/build-template.mjs --check   # exit 1 when an owned region is stale
//
// Parts, joined in order: the feature-essay head up to </head> (with this template's header comment),
// <style data-vpk-case-study> holding assets/lab/case-study-page.css, </head>, assets/lab/motion-case-study.body.html,
// <script data-vpk-lab-doc> holding assets/lab/motion-case-study.doc.mjs, feature-essay's body-level runtime tail
// (after its body-level </main>, up to </body>), then </body></html>. Then the lab block (lab/kit.mjs) and the
// runtime pipeline (kind template). --check compares only what this script owns: the case-study style, the
// body-level <main>, the doc script and the lab block. The head and tail belong to the runtime pipeline
// (build.mjs --refresh-library --check), so edits to feature-essay or other runtime blocks never break this check.
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildLabBlock, extractLabBlock, injectLabKit } from "./kit.mjs";

const SKILL = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
export const TEMPLATE_PATH = path.join(SKILL, "assets", "templates", "motion-case-study.html");
const SOURCES = Object.freeze({
	shell: path.join(SKILL, "assets", "templates", "feature-essay.html"),
	css: path.join(SKILL, "assets", "lab", "case-study-page.css"),
	body: path.join(SKILL, "assets", "lab", "motion-case-study.body.html"),
	doc: path.join(SKILL, "assets", "lab", "motion-case-study.doc.mjs"),
});
export const TEMPLATE_HEADER = [
	"<!-- ==================================================================",
	"     TEMPLATE · Motion case study (vpk-html) · film + cue sheet + Gantt + labs (vpk-lab kit)",
	"     Generated by scripts/lab/build-template.mjs from the feature-essay shell, assets/lab/ and the lab kit.",
	"     Self-contained offline HTML. No external requests. No decorative shadows.",
	"     ================================================================== -->",
].join("\n");
const STRIP_EXPORT = /^export (?=(async )?function|const|let|class)/gm;
const read = file => fs.readFileSync(file, "utf8");

/** Text after the shell's body-level </main> (the one before the theme runtime) up to its last </body>. */
export function runtimeTail(shell) {
	const marker = shell.indexOf("<!-- vpk-theme-runtime:start -->");
	const mainEnd = shell.lastIndexOf("</main>", marker < 0 ? shell.length : marker);
	const bodyEnd = shell.toLowerCase().lastIndexOf("</body>");
	if (mainEnd < 0 || bodyEnd < mainEnd) throw new Error("build-template: feature-essay.html has no body-level </main> before its runtimes");
	return shell.slice(mainEnd + "</main>".length, bodyEnd);
}

/** The shell head up to </head>, with the leading header comment replaced by TEMPLATE_HEADER. */
export function shellHead(shell) {
	const headEnd = shell.indexOf("</head>");
	if (headEnd < 0) throw new Error("build-template: feature-essay.html has no </head>");
	const head = shell.slice(0, headEnd);
	const open = head.indexOf("<!--");
	const close = head.indexOf("-->", open);
	if (open < 0 || close < 0 || open > head.indexOf("<html")) throw new Error("build-template: feature-essay.html lost its header comment");
	return `${head.slice(0, open)}${TEMPLATE_HEADER}${head.slice(close + 3)}`;
}

/** The doc script element: the sample lab with `export ` stripped. */
export function docScript(source = read(SOURCES.doc)) {
	return `<script data-vpk-lab-doc>\n${source.replace(STRIP_EXPORT, "").trim()}\n</script>`;
}

/** The assembled template before the lab block and the runtime pipeline. */
export function assembleTemplate({ shell = read(SOURCES.shell), css = read(SOURCES.css), body = read(SOURCES.body), doc = read(SOURCES.doc) } = {}) {
	return [
		shellHead(shell),
		`<style data-vpk-case-study>\n${css.trim()}\n</style>`,
		"</head>",
		body.trim(),
		docScript(doc),
		runtimeTail(shell).replace(/^\n+/, ""),
		"</body>",
		"</html>",
		"",
	].join("\n");
}

/** The finished template: assembled, lab block injected, runtime pipeline applied (kind template). */
export async function buildTemplateHtml(options = {}) {
	const { applyRuntimePipeline } = await import("../runtime/pipeline.mjs");
	return applyRuntimePipeline(injectLabKit(assembleTemplate(options)), { filePath: TEMPLATE_PATH, kind: "template" });
}

const between = (html, open, close) => {
	const start = html.indexOf(open);
	const end = start < 0 ? -1 : html.indexOf(close, start + open.length);
	return start < 0 || end < 0 ? null : html.slice(start, end + close.length);
};

/** The regions this script owns, for --check. */
export function ownedParts(html) {
	const bodyAt = html.search(/<body\b/i);
	return {
		style: between(html, "<style data-vpk-case-study>", "</style>"),
		main: bodyAt < 0 ? null : between(html.slice(bodyAt), "<main", "</main>"),
		doc: between(html, "<script data-vpk-lab-doc>", "</script>"),
		lab: extractLabBlock(html),
	};
}

/** Owned parts that differ from a fresh build: string[] (empty when current). */
export async function templateDrift(current, expected) {
	const want = ownedParts(expected ?? (await buildTemplateHtml()));
	const have = ownedParts(current);
	const drift = Object.keys(want).filter(key => have[key] !== want[key]);
	if (have.lab !== null && have.lab !== buildLabBlock()) drift.push("lab (kit.mjs)");
	return [...new Set(drift)];
}

async function main(argv) {
	const check = argv.includes("--check");
	const unknown = argv.filter(arg => arg !== "--check");
	if (unknown.length) {
		console.error(`Unknown argument(s): ${unknown.join(", ")}\nUsage: build-template.mjs [--check]`);
		return 2;
	}
	const rel = path.relative(process.cwd(), TEMPLATE_PATH);
	if (check) {
		if (!fs.existsSync(TEMPLATE_PATH)) {
			console.error(`✗ ${rel} is missing; run build-template.mjs`);
			return 1;
		}
		const drift = await templateDrift(read(TEMPLATE_PATH));
		if (drift.length) {
			console.error(`✗ ${rel}: stale ${drift.join(", ")}; run node .agents/skills/vpk-html/scripts/lab/build-template.mjs (unsandboxed)`);
			return 1;
		}
		console.log(`✓ ${rel}: case-study style, main, doc script and lab block are current`);
		return 0;
	}
	const html = await buildTemplateHtml();
	const before = fs.existsSync(TEMPLATE_PATH) ? read(TEMPLATE_PATH) : null;
	if (before !== html) fs.writeFileSync(TEMPLATE_PATH, html);
	console.log(`${before === html ? "unchanged" : "✓ wrote"} ${rel} (${Buffer.byteLength(html)} B)`);
	return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
	main(process.argv.slice(2)).then(code => {
		process.exitCode = code;
	}, error => {
		console.error(error.message);
		process.exitCode = 1;
	});
}
