import { expect, test } from "@playwright/test";
import { appUrl } from "@/tests/helpers/origin";

test("Reply and Draft instruction share the sticky work-item prompt", async ({ page }) => {
	await page.goto(appUrl("/sandbox/agent-selector-canvas?preview=vita-1-agent-sessions"));
	const preview = page.locator('[data-work-item-activity-preview="sessions"]');
	const prompt = preview.locator("[data-project-butter-comment-bar]");
	const editor = prompt.getByRole("textbox");
	const placeholder = () => editor.locator("p").first().evaluate((paragraph) => getComputedStyle(paragraph, "::before").content);
	const submit = prompt.getByRole("button", { name: "Submit", exact: true });
	await expect(preview.getByRole("button", { name: "Using an agent", exact: true })).toHaveAttribute("aria-expanded", "true");
	await expect(preview.getByRole("button", { name: "5 replies" })).toHaveAttribute("aria-expanded", "false");
	await expect(preview.getByRole("button", { name: "Draft instruction" })).toHaveCount(0);
	await expect.poll(placeholder).toContain("Give an instruction");
	await expect(submit).toBeDisabled();
	const stem = preview.locator("[data-jira-activity-thread-stem]:visible").first();
	const timeline = preview.getByRole("list", { name: "Activity timeline" });
	const activityMenu = preview.getByRole("button", { name: "Filter activity" });
	const expandChanges = page.getByRole("menuitemcheckbox", { name: "Expand change details" });
	await activityMenu.click();
	await expandChanges.click();
	if (await expandChanges.isVisible()) await page.keyboard.press("Escape");
	await expect(stem).toHaveCSS("background-image", /repeating-linear-gradient/);
	await preview.getByRole("button", { name: "Timeline", exact: true }).click();
	await activityMenu.click();
	await expect(expandChanges).toHaveAttribute("aria-checked", "true");
	await page.keyboard.press("Escape");
	await expect(stem).toHaveCSS("background-image", "none");
	await expect(timeline).toHaveCount(1);
	await expect(timeline.getByText(/Visuals are looking strong/)).toBeVisible();
	await expect(timeline.getByText("Thanks. Let's include both fixes in the next pass.", { exact: true })).toBeVisible();
	const timelineRows = timeline.locator(":scope > li[data-jira-activity-entry-id]");
	await expect(timelineRows).toHaveCount(5);
	await expect(timelineRows.nth(0).locator("[data-jira-activity-timeline-stem]")).toBeVisible();
	await expect(timelineRows.nth(2).locator("[data-jira-activity-timeline-stem]")).toBeVisible();
	await expect(preview.getByRole("button", { name: "Using an agent", exact: true })).toHaveCount(0);
	await preview.getByRole("button", { name: "Agent sessions", exact: true }).click();
	const summarize = preview.getByRole("button", { name: "Summarize thread" }).first();
	await summarize.focus();
	await summarize.press("Enter");
	await expect(preview.getByRole("button", { name: "Show replies", exact: true })).toBeFocused();
	await expect(preview.getByRole("img", { name: "Thread participants: Cursor, Venn, Annie Cook" })).toBeVisible();
	await expect(stem).toHaveCSS("background-image", /repeating-linear-gradient/);
	await expect(stem).toHaveCSS("mask-image", /linear-gradient.*20%/);
	await preview.getByRole("button", { name: "Timeline", exact: true }).click();
	await expect(stem).toHaveCSS("background-image", "none");
	await expect(stem).toHaveCSS("mask-image", "none");
	await expect(preview.getByRole("img", { name: /Thread participants/ })).toHaveCount(0);
	await expect(preview.getByRole("button", { name: "Show 4 more replies" })).toHaveAttribute("aria-expanded", "false");
	await expect(preview.getByRole("button", { name: "Draft instruction" })).toHaveCount(0);
	await preview.getByRole("button", { name: "Agent sessions", exact: true }).click();

	await preview.getByRole("button", { name: "Draft instruction" }).click();
	await expect(editor).toBeFocused();
	await expect(editor).toContainText("error summary");
	await expect.poll(placeholder).toBe("none");
	await expect(submit).toBeEnabled();
	await preview.getByRole("button", { name: "Show replies", exact: true }).click();
	await expect(preview.getByRole("group", { name: "Replies", exact: true }).getByText("Thanks. Let's include both fixes in the next pass.", { exact: true })).toBeVisible();
	const replies = preview.getByRole("group", { name: "Replies", exact: true }).first();
	const disclosure = preview.locator("[data-jira-activity-replies-disclosure]:visible").filter({ has: page.getByRole("button", { name: "Hide replies", exact: true }) });
	await expect(disclosure).toHaveCSS("padding-bottom", "4px");
	await expect(disclosure.locator(":scope > [data-jira-activity-thread-continuation]")).toHaveCSS("mask-image", "none");
	await expect(replies.locator("[data-jira-activity-thread-continuation]").first()).toHaveCSS("background-image", "none");
	await expect(replies.locator("[data-jira-activity-thread-branch]").first()).toHaveCSS("border-left-style", "solid");
	await expect(preview.getByRole("img", { name: /Thread participants/ })).toHaveCount(0);
	await expect(preview.getByRole("button", { name: "Draft instruction" })).toHaveCount(0);

	const reply = preview.getByRole("button", { name: "Reply", exact: true }).first();
	await reply.focus();
	await reply.press("Enter");
	await expect(editor).toBeFocused();
	await expect(preview.getByRole("textbox")).toHaveCount(1);
	await expect(prompt).toContainText("Replying to Review the onboarding flow");
	await expect.poll(placeholder).toContain("Give an instruction");
	await expect(submit).toBeDisabled();
	await editor.fill("Please verify keyboard navigation.");
	await submit.click();
	await expect(preview.getByText("Please verify keyboard navigation.", { exact: true }).filter({ visible: true })).toBeVisible();
	await expect(preview.getByRole("button", { name: "Show 5 more replies" })).toHaveAttribute("aria-expanded", "false");
	await expect(preview.getByText("Thanks. Let's include both fixes in the next pass.", { exact: true }).filter({ visible: true })).toHaveCount(0);
	await preview.getByRole("button", { name: "Show 5 more replies" }).click();

	await summarize.focus();
	await summarize.press("Enter");
	await preview.getByRole("button", { name: "Draft instruction" }).click();
	await expect.poll(placeholder).toBe("none");
	await expect(submit).toBeEnabled();
	await submit.click();
	await expect(preview.getByText(/^Update the account setup validation messages/).filter({ visible: true })).toBeVisible();
	await expect(preview.getByRole("button", { name: "Show 6 more replies" })).toHaveAttribute("aria-expanded", "false");
	await expect(preview.getByText("Please verify keyboard navigation.", { exact: true }).filter({ visible: true })).toHaveCount(0);
	await expect(preview.getByText("Instruction added to this demo session")).toHaveCount(0);
	await expect(preview.getByText("👀", { exact: true }).filter({ visible: true })).toBeVisible();
	await expect(preview.getByRole("button", { name: "Working", exact: true })).toBeVisible();
	await expect.poll(placeholder).toContain("Give an instruction");
	await expect(submit).toBeDisabled();
});
