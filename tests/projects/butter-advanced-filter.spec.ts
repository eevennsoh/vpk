import { expect, test } from "@playwright/test";
import { appUrl } from "@/tests/helpers/origin";

test("advanced clear uses the same full-width menu row", async ({ page }) => {
	await page.goto(appUrl("/butter-v1"));
	await page.getByRole("button", { name: "Filter board", exact: true }).click();
	await page.getByRole("menuitem", { name: "Agent status Open submenu" }).hover();
	const standard = page.getByRole("menu", { name: "Agent status filter options" }).getByRole("menuitem", { name: "Clear", exact: true });
	const styles = (element: Element) => { const style = getComputedStyle(element); return { height: style.height, padding: style.padding, radius: style.borderRadius, fontSize: style.fontSize, weight: style.fontWeight }; };
	const reference = await standard.evaluate(styles);
	await page.getByRole("menuitem", { name: "Advanced Open submenu" }).hover();
	const panel = page.getByRole("dialog", { name: "Advanced filter" });
	const clear = panel.getByRole("menuitem", { name: "Clear", exact: true });
	await expect(clear).toBeVisible();
	expect(await clear.evaluate(styles)).toEqual(reference);
	const widths = await panel.evaluate((element) => ({ panel: element.getBoundingClientRect().width, row: element.querySelector('[role="menuitem"]')!.getBoundingClientRect().width }));
	expect(widths.panel - widths.row).toBe(12);
});

test("advanced filter applies conditions immediately and uses removable tags", async ({ page }) => {
	await page.setViewportSize({ width: 1800, height: 1000 });
	await page.goto(appUrl("/butter-v1"));
	await page.getByRole("button", { name: "Filter board", exact: true }).click();
	await page.getByRole("menuitem", { name: "Advanced Open submenu" }).hover();
	const panel = page.getByRole("dialog", { name: "Advanced filter" });
	await expect(panel.getByText("Example conditions")).toHaveCount(0);
	await expect(panel.getByRole("button", { name: "Apply example" })).toHaveCount(0);
	await expect(panel.getByRole("combobox", { name: "Field 1" })).toHaveText("Attribute");
	await expect(page.getByRole("group", { name: "Applied filters" })).toHaveCount(0);
	await panel.getByRole("combobox", { name: "Field 1" }).click();
	await page.getByRole("option", { name: "Agent status", exact: true }).click();
	await panel.getByRole("combobox", { name: "Value 1" }).fill("Needs input");
	await page.getByRole("option", { name: "Needs input", exact: true }).click();
	await expect(page.getByRole("group", { name: "Agent status is Needs input" })).toBeVisible();
	await expect(panel.locator('[data-slot="tag"]').filter({ hasText: "Needs input" })).toBeVisible();
	await panel.getByRole("button", { name: "Add condition" }).click();
	await panel.getByRole("combobox", { name: "Field 2" }).click();
	await page.getByRole("option", { name: "Status", exact: true }).click();
	await panel.getByRole("combobox", { name: "Value 2" }).fill("In review");
	await page.getByRole("option", { name: "In review", exact: true }).click();
	await expect(page.getByRole("group", { name: "Status is In review" })).toBeVisible();
	await expect(page.getByRole("button", { name: "PAY-112: Confirm the sandbox key retention window before replay" })).toBeVisible();
	await panel.getByRole("combobox", { name: "Operator 1" }).click();
	await page.getByRole("option", { name: "is not", exact: true }).click();
	await expect(page.getByRole("group", { name: "Agent status is not Needs input" })).toBeVisible();
	await expect(panel).toBeVisible();
	const input = panel.getByRole("combobox", { name: "Value 1" });
	await input.fill("Working");
	await page.getByRole("option", { name: "Working", exact: true }).click();
	await expect(page.getByRole("group", { name: "Agent status is not Needs input +1" })).toBeVisible();
	await panel.getByRole("button", { name: "Remove Needs input", exact: true }).click();
	await expect(page.getByRole("group", { name: "Agent status is not Working" })).toBeVisible();
	await panel.getByRole("button", { name: "Add condition" }).click();
	await panel.getByRole("combobox", { name: "Field 3" }).press("Enter");
	await page.getByRole("option", { name: "Pull request", exact: true }).press("Enter");
	await panel.getByRole("combobox", { name: "Value 3" }).fill("Open");
	await page.getByRole("option", { name: "Open", exact: true }).click();
	await expect(page.getByRole("group", { name: "Pull request is Open" })).toBeVisible();
	const clear = panel.getByRole("menuitem", { name: "Clear", exact: true });
	const width = await clear.evaluate((element) => element.getBoundingClientRect().width);
	await clear.click({ position: { x: width - 4, y: 16 } });
	await expect(page.getByRole("group", { name: "Applied filters" })).toHaveCount(0);
	await expect(panel).toBeVisible();
	await expect(panel.getByRole("combobox", { name: "Field 1" })).toBeVisible();
	await expect(panel.getByText("Example conditions")).toHaveCount(0);
	await expect(panel.getByRole("combobox", { name: "Field 2" })).toHaveCount(0);
});
