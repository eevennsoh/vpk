test("a reply to an ordinary comment also collapses older replies", async ({ page }) => {
	await page.setViewportSize({ width: 1600, height: 1100 });
	await page.emulateMedia({ reducedMotion: "reduce" });
	await page.goto(appUrl("/butter-v1"));
	await page.getByRole("button", { name: "Select Work item", exact: true }).click();
	await page.getByRole("button", { name: "Close gallery", exact: true }).click();
	const thread = page.locator('[data-project-butter-activity-feed] [data-jira-activity-entry-id="butter-source-comment-1"]');
	await thread.getByRole("button", { name: /Show 1 reply/u }).click();
	await expect(thread.getByText(/Checked the campaign palette/u)).toBeVisible();
	await thread.getByRole("button", { name: "Reply", exact: true }).first().focus();
	await page.keyboard.press("Enter");
	const composer = page.getByRole("form", { name: "Comment editor" });
	await composer.getByRole("textbox", { name: "Comment editor" }).fill("A new comment reply");
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expect(thread.getByRole("button", { name: /Show 2 replies/u })).toHaveAttribute("aria-expanded", "false");
	await expect(thread.getByText(/Checked the campaign palette/u)).toBeHidden();
	await expect(thread.getByText("A new comment reply", { exact: true })).toBeVisible();
});

test("posting in another session keeps each thread's latest reply visible", async ({ page }) => {
	await page.setViewportSize({ width: 1600, height: 1100 });
	await page.emulateMedia({ reducedMotion: "reduce" });
	await page.goto(appUrl("/butter-v1"));
	await page.getByRole("button", { name: "Select Work item", exact: true }).click();
	await page.getByRole("button", { name: "Close gallery", exact: true }).click();
	const activity = page.getByRole("region", { name: "Activity", exact: true });
	await activity.getByRole("tab", { name: "Agent sessions", exact: true }).click();
	const first = activity.locator('[data-jira-activity-entry-id="invocation-butter-cursor-forecast"]:visible');
	await first.getByRole("button", { name: "Draft instruction" }).click();
	const composer = page.getByRole("form", { name: "Comment editor" });
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expect(first.getByText(/Follow up on the work-item discussion/u)).toBeVisible();
	await activity.getByRole("button", { name: "Other agent activity", exact: true }).click();
	const second = activity.locator('[data-jira-activity-entry-id="invocation-butter-coding"]:visible');
	await second.getByRole("button", { name: "Show replies", exact: true }).click();
	await second.getByRole("button", { name: "Reply", exact: true }).first().focus();
	await page.keyboard.press("Enter");
	await composer.getByRole("textbox", { name: "Comment editor" }).fill("Second session update");
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expect(second.getByText("Second session update", { exact: true })).toBeVisible();
	await expect(first.getByText(/Follow up on the work-item discussion/u)).toBeVisible();
	await expect(first.getByRole("button", { name: /Show 5 replies/u })).toHaveAttribute("aria-expanded", "false");
});
