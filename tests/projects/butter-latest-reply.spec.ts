import { expect, test } from "@playwright/test";
import { appUrl } from "@/tests/helpers/origin";

test("posting a reply shows only the latest reply in both activity views", async ({ page }) => {
	await page.setViewportSize({ width: 1600, height: 1100 });
	await page.emulateMedia({ reducedMotion: "reduce" });
	await page.goto(appUrl("/butter-v1"));
	await page.getByRole("button", { name: "Select Work item", exact: true }).click();
	await page.getByRole("button", { name: "Close gallery", exact: true }).click();
	const activity = page.getByRole("region", { name: "Activity", exact: true });
	await activity.getByRole("tab", { name: "Agent sessions", exact: true }).click();
	const thread = activity.locator('[data-jira-activity-entry-id="invocation-butter-cursor-forecast"]:visible');
	const expectReplyControl = async (count: number) => {
		const label = `Show ${count} replies`;
		const toggle = thread.getByRole("button", { name: new RegExp(`^${label}`, "u") });
		await expect(toggle).toHaveAttribute("aria-expanded", "false");
		const labelBox = await toggle.getByText(label, { exact: true }).boundingBox();
		const avatars = toggle.getByRole("group", { name: /^Reply participants:/u });
		await expect(avatars).toBeVisible();
		const avatarBox = await avatars.boundingBox();
		if (!labelBox || !avatarBox) throw new Error("Missing reply label or participant avatars");
		expect(avatarBox.x).toBeGreaterThanOrEqual(labelBox.x + labelBox.width);
	};
	await thread.getByRole("button", { name: "Show replies", exact: true }).click();
	await expect(thread.getByText("Did you check the account setup step?", { exact: true })).toBeVisible();
	await thread.getByRole("button", { name: "Summarize thread" }).focus();
	await page.keyboard.press("Enter");
	await thread.getByRole("button", { name: "Draft instruction" }).click();
	const composer = page.getByRole("form", { name: "Comment editor" });
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expectReplyControl(5);
	await expect(thread.getByText("Did you check the account setup step?", { exact: true })).toBeHidden();
	await expect(thread.getByText(/Follow up on the work-item discussion/u)).toBeVisible();
	await thread.getByRole("button", { name: /Show 5 replies/u }).click();
	await expect(thread.getByText("Did you check the account setup step?", { exact: true })).toBeVisible();
	await thread.getByRole("button", { name: "Reply", exact: true }).first().focus();
	await page.keyboard.press("Enter");
	await composer.getByRole("textbox", { name: "Comment editor" }).fill("A second follow-up");
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expect(thread.getByRole("button", { name: /Show 6 replies/u })).toHaveAttribute("aria-expanded", "false");
	await expect(thread.getByText("A second follow-up", { exact: true })).toBeVisible();
	await expect(thread.getByText(/Follow up on the work-item discussion/u)).toBeHidden();
	await activity.getByRole("tab", { name: "Timeline", exact: true }).click();
	await expect(thread.getByText("A second follow-up", { exact: true })).toBeVisible();
	await expect(thread.getByText(/Follow up on the work-item discussion/u)).toBeHidden();
	await expectReplyControl(6);
	await thread.getByRole("button", { name: /Show 6 replies/u }).click();
	await thread.getByRole("button", { name: "Reply", exact: true }).first().focus();
	await page.keyboard.press("Enter");
	await composer.getByRole("textbox", { name: "Comment editor" }).fill("A third follow-up");
	await composer.getByRole("button", { name: "Submit", exact: true }).click();
	await expect(thread.getByRole("button", { name: /Show 7 replies/u })).toHaveAttribute("aria-expanded", "false");
	await expect(thread.getByText("A third follow-up", { exact: true })).toBeVisible();
	await expect(thread.getByText("A second follow-up", { exact: true })).toBeHidden();
});

