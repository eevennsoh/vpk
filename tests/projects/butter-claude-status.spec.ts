import { expect, test } from "@playwright/test";
import { appUrl } from "@/tests/helpers/origin";

test("Claude's status change appears once throughout the working journey", async ({ page }) => {
	await page.emulateMedia({ reducedMotion: "reduce" });
	await page.goto(appUrl("/butter"));
	const card = page.locator('[data-issue-key="PAY-999"][data-board-column-title] [data-slot="jira-issue-card"]');
	await page.getByRole("button", { name: "In progress", exact: true }).click();
	await card.click();
	const item = page.getByRole("dialog", { name: "Project butter" });
	const statusChange = item.locator('[data-jira-activity-entry-id^="merchant-status-"]');
	await expect(statusChange).toHaveCount(1);
	await expect(statusChange).toContainText("Claude changed status from To do → In progress");
	const thread = item.locator('[data-jira-activity-entry-id^="invocation-"]');
	await expect(thread.locator('[data-jira-activity-entry-id^="merchant-status-"]')).toHaveCount(1);
	await expect(statusChange.locator("[data-jira-activity-thread-branch]")).toBeVisible();
	const branch = await statusChange.locator("[data-jira-activity-thread-branch]").boundingBox();
	const replyBranch = await thread.getByRole("group", { name: "Replies" }).locator("[data-jira-activity-thread-branch]").first().boundingBox();
	if (!branch || !replyBranch) throw new Error("Expected both thread branches");
	expect(branch.x).toBeCloseTo(replyBranch.x, 0);
	await expect(thread.locator('[data-project-butter-session-start]')).toBeVisible();
	const sessionBounds = await thread.locator('[data-project-butter-session-start]').boundingBox();
	const replyBounds = await thread.locator('[data-jira-activity-reply-header]').first().boundingBox();
	if (!sessionBounds || !replyBounds) throw new Error("Expected the session card and reply header");
	expect(replyBounds.y - sessionBounds.y - sessionBounds.height).toBeCloseTo(24, 0);
	await item.getByRole("button", { name: "Close Project butter work item" }).click();
	await page.getByRole("button", { name: "Pull request", exact: true }).click();
	await card.click();
	await expect(statusChange).toHaveCount(1);
	await item.getByRole("button", { name: "Close Project butter work item" }).click();
	await page.getByRole("button", { name: "Prepare & invoke", exact: true }).click();
	await expect(statusChange).toHaveCount(0);
});
