function at(iso: string): { timestamp: string; ageMs: number } {
	const ms = Date.parse(iso);
	const date = new Date(ms);
	const hours = String(date.getUTCHours()).padStart(2, "0");
	const minutes = String(date.getUTCMinutes()).padStart(2, "0");
	return {
		timestamp: `${date.getUTCDate()} ${MONTHS[date.getUTCMonth()]} ${date.getUTCFullYear()} at ${hours}:${minutes}`,
		ageMs: STORY_NOW_MS - ms,
	};
}

